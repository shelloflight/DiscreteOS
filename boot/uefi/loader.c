/*
 * D-OS UEFI loader (\EFI\BOOT\BOOTX64.EFI). The UEFI twin of boot/stage1+2+3: it hands the kernel
 * exactly the machine state and BootInfo (v5) the BIOS path does, so the kernel has one entry
 * contract. Reference: docs/boot.md.
 *
 *   1. Read \DOS\KERNEL.BIN from the volume this loader came from; verify its signature, check
 *      its image header
 *   2. Place it at its physical load address (1 MiB), zero its .bss, and relocate it to a random
 *      virtual base (KASLR, boot/common/kaslr.c; entropy from EFI_RNG_PROTOCOL + the CPU)
 *   3. Collect what the kernel needs from the firmware: GOP framebuffer, ACPI RSDP
 *   4. Reserve low memory: BootInfo + memory map, boot page tables, the AP trampoline page
 *   5. Build page tables like stage 2 (identity map + kernel half), exit boot services,
 *      convert the UEFI memory map to E820 types, jump to the kernel with RDI = &BootInfo
 *
 * Everything the firmware returns is checked before use; on any failure the loader reports it
 * and returns to the firmware (which then tries its next boot option).
 */

