/* Reads a whole file from the boot volume into pool memory. */
static efi_status read_file(efi_file *root, const char16 *path, const char *name, uint64_t min, uint64_t max,
                            uint8_t **out, uint64_t *size)
{
    efi_file *f;
    efi_status s = root->open(root, &f, path, EFI_FILE_MODE_READ, 0);
    if (s) {
        say("D-OS: UEFI loader: %s not found on the boot volume\n", name);
        return s;
    }
    uint64_t len = 0;
    if ((s = f->set_position(f, ~0ull)) || (s = f->get_position(f, &len)) || (s = f->set_position(f, 0)) || len < min || len > max) {
        f->close(f);
        say("D-OS: UEFI loader: %s: size out of range\n", name);
        return s ? s : EFI_LOAD_ERROR;
    }
    uint8_t *buf;
    if ((s = bs->allocate_pool(EFI_LOADER_DATA, len ? len : 1, (void **)&buf))) {
        f->close(f);
        return s;
    }
    uint64_t done = 0;
    while (done < len) {
        uint64_t n = len - done;
        if ((s = f->read(f, &n, buf + done)) || n == 0) {
            f->close(f);
            say("D-OS: UEFI loader: %s: read error\n", name);
            return s ? s : EFI_LOAD_ERROR;
        }
        done += n;
    }
    f->close(f);
    *out = buf;
    *size = len;
    return EFI_SUCCESS;
}

/* The kernel and its signature from the volume this loader was started from. */
static efi_status read_kernel(efi_handle image, uint8_t **out, uint64_t *size, uint8_t **sig)
{
    static const efi_guid li_guid = GUID_LOADED_IMAGE, fs_guid = GUID_SIMPLE_FS;
    efi_loaded_image *li;
    efi_simple_fs *fs;
    efi_file *root;
    efi_status s = bs->handle_protocol(image, &li_guid, (void **)&li);
    if (s)
        return fail(s, "no loaded-image protocol");
    if ((s = bs->handle_protocol(li->device, &fs_guid, (void **)&fs)))
        return fail(s, "the boot volume has no file system");
    if ((s = fs->open_volume(fs, &root)))
        return fail(s, "cannot open the boot volume");
    uint64_t siglen;
    if ((s = read_file(root, KERNEL_FILE, "\\DOS\\KERNEL.BIN", sizeof(struct kernel_header), KERNEL_MAX_FILE, out, size)) ||
        (s = read_file(root, KERNEL_SIG_FILE, "\\DOS\\KERNEL.DSIG", DSIG_SIZE, DSIG_SIZE, sig, &siglen))) {
        root->close(root);
        return fail(s, "cannot read the kernel");
    }
    root->close(root);
    return EFI_SUCCESS;
}

/* Measured boot: when the firmware has a TPM 2.0 (TCG2 protocol), extend PCR 8 with the kernel's
 * signed .dsig header (it commits to the kernel's SHA-512, size, name and signing key) and log it
 * in the firmware's event log. The kernel replays the same event into its own log. */
static bool measure_kernel(const uint8_t *sig)
{
    static const efi_guid tcg2_guid = GUID_TCG2;
    efi_tcg2 *tcg2;
    if (bs->locate_protocol(&tcg2_guid, NULL, (void **)&tcg2) || !tcg2) {
        say("D-OS: no TPM (TCG2) from the firmware: the kernel measures itself if it finds one\n");
        return false;
    }
    static efi_tcg2_event ev;
    static const char text[] = "D-OS kernel KERNEL.BIN";
    memset(&ev, 0, sizeof(ev));
    ev.header_size = 14;
    ev.header_version = 1;
    ev.pcr = PCR_KERNEL;
    ev.event_type = EV_IPL;
    memcpy(ev.event, text, sizeof(text));
    ev.size = (uint32_t)(sizeof(ev) - sizeof(ev.event) + sizeof(text));
    efi_status s = tcg2->hash_log_extend_event(tcg2, 0, (uint64_t)(uintptr_t)sig, DSIG_SIGNED, &ev);
    if (s) {
        say("D-OS: TPM measurement of the kernel failed (status %x)\n", s);
        return false;
    }
    say("D-OS: kernel measured into TPM PCR %u\n", (uint64_t)PCR_KERNEL);
    return true;
}

static efi_status check_header(const struct kernel_header *h, uint64_t file_len)
{
    const char *why = kaslr_check_header(h, file_len);
    return why ? fail(EFI_LOAD_ERROR, why) : EFI_SUCCESS;
}

/* KASLR entropy: the firmware's RNG when it has one, mixed with the CPU's (kaslr_entropy). */
static uint32_t gather_entropy(uint8_t out[64])
{
    static const efi_guid rng_guid = GUID_RNG;
    efi_rng *rng;
    uint8_t fw[32];
    bool have = !bs->locate_protocol(&rng_guid, NULL, (void **)&rng) && rng && !rng->get_rng(rng, NULL, sizeof(fw), fw);
    uint32_t src = kaslr_entropy(have ? fw : NULL, have ? sizeof(fw) : 0, KASLR_SRC_EFI_RNG, out);
    memset(fw, 0, sizeof(fw));
    return src;
}

static const char *source_text(uint32_t s)
{
    if (s & KASLR_SRC_EFI_RNG)
        return (s & (KASLR_SRC_RDSEED | KASLR_SRC_RDRAND)) ? "EFI RNG + CPU" : "EFI RNG";
    if (s & KASLR_SRC_RDSEED)
        return "RDSEED";
    return (s & KASLR_SRC_RDRAND) ? "RDRAND" : "TSC only";
}

static void find_framebuffer(struct bootinfo *bi)
{
    static const efi_guid gop_guid = GUID_GOP;
    efi_gop *gop;
    if (bs->locate_protocol(&gop_guid, NULL, (void **)&gop) || !gop || !gop->mode || !gop->mode->info) {
        say("D-OS: no GOP framebuffer (serial console only)\n");
        return;
    }
    const efi_gop_mode_info *m = gop->mode->info;
    uint8_t r, g, b;
    switch (m->pixel_format) {
    case GOP_RGBX: r = 0; g = 8; b = 16; break;
    case GOP_BGRX: r = 16; g = 8; b = 0; break;
    case GOP_BITMASK: {
        uint32_t masks[3] = { m->red_mask, m->green_mask, m->blue_mask };
        uint8_t shifts[3];
        for (int i = 0; i < 3; i++) {
            int k = 0;
            while (k < 32 && masks[i] != 0xFFu << k)
                k += 8;
            if (k >= 32) {
                say("D-OS: GOP pixel masks are not 8-bit channels (serial console only)\n");
                return;
            }
            shifts[i] = (uint8_t)k;
        }
        r = shifts[0]; g = shifts[1]; b = shifts[2];
        break;
    }
    default:
        say("D-OS: GOP has no linear framebuffer (serial console only)\n");
        return;
    }
    bi->fb_type = 1;
    bi->fb_base = gop->mode->fb_base;
    bi->fb_size = gop->mode->fb_size;
    bi->fb_width = m->width;
    bi->fb_height = m->height;
    bi->fb_pitch = m->pixels_per_scan_line * 4;
    bi->fb_red_shift = r;
    bi->fb_green_shift = g;
    bi->fb_blue_shift = b;
    say("D-OS: GOP framebuffer %ux%u at %x\n", (uint64_t)m->width, (uint64_t)m->height, bi->fb_base);
}

static void find_acpi(struct bootinfo *bi)
{
    static const efi_guid acpi20 = GUID_ACPI_20, acpi10 = GUID_ACPI_10;
    uint64_t v1 = 0;
    for (uint64_t i = 0; i < st->table_count; i++) {
        if (guid_eq(&st->tables[i].guid, &acpi20)) {
            bi->rsdp = (uint64_t)(uintptr_t)st->tables[i].table;
            say("D-OS: ACPI 2.0 RSDP at %x\n", bi->rsdp);
            return;
        }
        if (guid_eq(&st->tables[i].guid, &acpi10))
            v1 = (uint64_t)(uintptr_t)st->tables[i].table;
    }
    bi->rsdp = v1;
    say(v1 ? "D-OS: ACPI 1.0 RSDP at %x\n" : "D-OS: no ACPI tables from the firmware\n", v1);
}

static efi_status alloc_low(uint64_t pages, uint32_t type, uint64_t *out)
{
    uint64_t a = LOW_LIMIT;
    efi_status s = bs->allocate_pages(ALLOCATE_MAX_ADDRESS, type, pages, &a);
    if (s)
        return s;
    memset((void *)(uintptr_t)a, 0, pages * PAGE);
    *out = a;
    return EFI_SUCCESS;
}

static uint32_t e820_type(uint32_t t)
{
    switch (t) {
    case EFI_LOADER_CODE: case EFI_LOADER_DATA: case EFI_BS_CODE: case EFI_BS_DATA: case EFI_CONVENTIONAL:
        return MMAP_USABLE;           /* boot services are gone once the kernel runs */
    case EFI_ACPI_RECLAIM: return MMAP_ACPI_RECLAIMABLE;
    case EFI_ACPI_NVS:     return MMAP_ACPI_NVS;
    case EFI_UNUSABLE:     return MMAP_BAD;
    default:               return MMAP_RESERVED;   /* runtime services, MMIO, persistent, unaccepted, ... */
    }
}

/* The UEFI map -> sorted, merged E820 entries. Usable RAM above `top` (not identity-mapped) is
 * left out. False if it does not fit. Runs after ExitBootServices: memory writes only. The
 * entries are first written over the map buffer itself (an E820 entry is smaller than a UEFI
 * descriptor, so entry i never overwrites a descriptor not yet read), then sorted and merged. */
static bool convert_map(uint8_t *map, uint64_t map_size, uint64_t desc_size, struct mmap_entry *out,
                        uint32_t *count, uint64_t top)
{
    struct mmap_entry *tmp = (struct mmap_entry *)map;
    uint64_t n = 0;
    for (uint64_t off = 0; off + sizeof(efi_memory_descriptor) <= map_size; off += desc_size) {
        efi_memory_descriptor d = *(const efi_memory_descriptor *)(map + off);
        if (!d.pages || d.pages > (1ull << 52) / PAGE)
            continue;
        uint64_t base = d.phys_start, len = d.pages * PAGE;
        uint32_t type = e820_type(d.type);
        if (type == MMAP_USABLE) {
            if (base >= top)
                continue;
            if (base + len > top)
                len = top - base;
        }
        tmp[n++] = (struct mmap_entry){ base, len, type, 1 };
    }
    for (uint64_t i = 1; i < n; i++) {           /* insertion sort: the map is nearly sorted */
        struct mmap_entry e = tmp[i];
        uint64_t j = i;
        while (j > 0 && tmp[j - 1].base > e.base) {
            tmp[j] = tmp[j - 1];
            j--;
        }
        tmp[j] = e;
    }
    uint32_t k = 0;
    for (uint64_t i = 0; i < n; i++) {
        if (k && out[k - 1].type == tmp[i].type && out[k - 1].base + out[k - 1].length == tmp[i].base) {
            out[k - 1].length += tmp[i].length;
            continue;
        }
        if (k == BOOTINFO_MMAP_MAX)
            return false;
        out[k++] = tmp[i];
    }
    *count = k;
    return k > 0;
}

/* Page tables like stage 2 + 3: identity map of [0, top) (1 GiB pages where the CPU has them,
 * else 2 MiB pages) and the first GiB again at the kernel's randomized base `kbase`. Tables live
 * in low memory, which the kernel's frame allocator never hands out, so they stay intact until the
 * kernel switches. */
static efi_status build_tables(uint64_t top, bool gb_pages, uint64_t kbase, uint64_t *cr3)
{
    uint64_t gibs = top / GIB;
    uint64_t pds = gb_pages ? 0 : gibs;
    uint64_t base;
    efi_status s = alloc_low(5 + pds, EFI_LOADER_DATA, &base);   /* PML4, 2 PDPTs, 2 kernel-window PDs */
    if (s)
        return fail(s, "no low memory for the boot page tables");
    uint64_t *pml4 = (uint64_t *)(uintptr_t)base;
    uint64_t *pdpt_lo = (uint64_t *)(uintptr_t)(base + PAGE);
    uint64_t *pdpt_hi = (uint64_t *)(uintptr_t)(base + 2 * PAGE);
    uint64_t pd0 = base + 5 * PAGE;              /* PDs of the identity map (2 MiB pages) */
    pml4[0] = (base + PAGE) | PT_P | PT_W;
    pml4[511] = (base + 2 * PAGE) | PT_P | PT_W;
    for (uint64_t g = 0; g < gibs; g++)
        pdpt_lo[g] = gb_pages ? (g * GIB) | PT_P | PT_W | PT_PS : (pd0 + g * PAGE) | PT_P | PT_W;
    for (uint64_t g = 0; g < pds; g++) {
        uint64_t *pd = (uint64_t *)(uintptr_t)(pd0 + g * PAGE);
        for (uint64_t i = 0; i < 512; i++)
            pd[i] = (g * GIB + i * (2ull << 20)) | PT_P | PT_W | PT_PS;
    }
    kaslr_map_window(pdpt_hi, kbase, base + 3 * PAGE, base + 4 * PAGE);   /* kbase -> physical 0..1 GiB */
    *cr3 = base;
    return EFI_SUCCESS;
}

efi_status efi_main(efi_handle image, efi_system_table *systab);
efi_status efi_main(efi_handle image, efi_system_table *systab)
{
    uint64_t tsc0 = rdtsc();
    st = systab;
    bs = st->boot_services;
    say("D-OS: UEFI loader\n");

    uint64_t cr4;
    __asm__ volatile("mov %%cr4, %0" : "=r"(cr4));
    if (cr4 & (1ull << 12))
        return fail(EFI_UNSUPPORTED, "5-level paging is active; D-KRNL uses 4-level paging");
    uint32_t r[4];
    cpuid(0x80000000u, r);
    bool gb_pages = false;
    if (r[0] >= 0x80000001u) {
        cpuid(0x80000001u, r);
        gb_pages = (r[3] >> 26) & 1;
    }

    /* 1-2: kernel */
    uint8_t *file, *sig;
    uint64_t file_len;
    mark("start");
    efi_status s = read_kernel(image, &file, &file_len, &sig);
    if (s)
        return s;
    mark("read kernel");
    /* Verified boot: nothing of the kernel is used before its signature checks out (the D-OS key
     * is built into this loader; docs/signing.md). */
    enum dsig_result vr = dsig_verify(sig, DSIG_KIND_KERNEL, dos_trusted_key, file, file_len, NULL);
    if (vr != DSIG_OK) {
        say("D-OS: kernel signature check failed: %s\n", dsig_result_text(vr));
        return fail(EFI_SECURITY_VIOLATION, "refusing to boot an unverified kernel");
    }
    mark("verify");
    uint8_t key_id[16];
    dsig_key_id(dos_trusted_key, key_id);
    say("D-OS: kernel signature valid (Ed25519, key %x)\n", (uint64_t)key_id[0] << 56 | (uint64_t)key_id[1] << 48 |
        (uint64_t)key_id[2] << 40 | (uint64_t)key_id[3] << 32 | (uint64_t)key_id[4] << 24 | (uint64_t)key_id[5] << 16 |
        (uint64_t)key_id[6] << 8 | key_id[7]);
    const struct kernel_header *h = (const struct kernel_header *)file;
    if ((s = check_header(h, file_len)))
        return s;
    uint64_t kpages = (h->mem_size + PAGE - 1) / PAGE, kphys = h->phys_base;
    if ((s = bs->allocate_pages(ALLOCATE_ADDRESS, EFI_LOADER_DATA, kpages, &kphys)))
        return fail(s, "the kernel's load address is not free memory");
    memcpy((void *)(uintptr_t)kphys, file, h->file_size);
    memset((void *)(uintptr_t)(kphys + h->file_size), 0, h->mem_size - h->file_size);
    say("D-OS: kernel %u KiB loaded at %x (%s)\n", h->file_size >> 10, kphys, "\\DOS\\KERNEL.BIN");
    mark("load");

    /* KASLR: a random base for the image; its relocations are applied to the loaded copy (the
     * verified file stays as it is). The base itself is never printed. */
    uint8_t rnd[64];
    uint32_t sources = gather_entropy(rnd);
    uint64_t kbase = kaslr_pick_base(rnd);
    uint64_t delta = kbase - KASLR_LINK_BASE;
    const char *why = kaslr_relocate((uint8_t *)(uintptr_t)kphys, h, delta);
    if (why) {
        say("D-OS: %s\n", why);
        return fail(EFI_LOAD_ERROR, "refusing to boot a kernel with a bad relocation table");
    }
    say("D-OS: kernel relocated (KASLR, %u bits, %s)\n", (uint64_t)KASLR_BITS, source_text(sources));
    mark("KASLR");

    /* 4: low memory. The AP trampoline page is claimed so no runtime data sits there. */
    uint64_t tramp = TRAMPOLINE_PHYS;
    if (bs->allocate_pages(ALLOCATE_ADDRESS, EFI_LOADER_DATA, 1, &tramp))
        say("D-OS: warning: the AP trampoline page %x is in use by the firmware\n", (uint64_t)TRAMPOLINE_PHYS);
    uint64_t bi_pa, ho_pa;
    const uint64_t bi_pages = 1 + (BOOTINFO_MMAP_MAX * sizeof(struct mmap_entry) + PAGE - 1) / PAGE;
    if ((s = alloc_low(bi_pages, EFI_LOADER_DATA, &bi_pa)))
        return fail(s, "no low memory for BootInfo");
    if ((s = alloc_low(2, EFI_LOADER_CODE, &ho_pa)))   /* code: firmware NX policies must allow it */
        return fail(s, "no low memory for the hand-off code");
    struct bootinfo *bi = (struct bootinfo *)(uintptr_t)bi_pa;
    struct mmap_entry *mm = (struct mmap_entry *)(uintptr_t)(bi_pa + PAGE);
    bi->magic = BOOTINFO_MAGIC;
    bi->version = BOOTINFO_VERSION;
    bi->firmware = 2;
    bi->mmap_addr = bi_pa + PAGE;
    bi->kernel_phys = kphys;
    bi->kernel_size = h->file_size;
    bi->tsc_stage1 = tsc0;
    bi->efi_system_table = (uint64_t)(uintptr_t)st;
    memcpy(bi->kernel_dsig, sig, DSIG_SIZE);
    bi->flags = BOOT_KERNEL_VERIFIED;
    bi->kernel_virt = h->virt_base + delta;
    bi->kaslr_sources = sources;
    memcpy(bi->seed, rnd + 32, sizeof(bi->seed));   /* bytes 0-7 chose the base: not reused */
    memset(rnd, 0, sizeof(rnd));
    mark("BootInfo");
    if (measure_kernel(sig))
        bi->flags |= BOOT_KERNEL_MEASURED;
    mark("TPM");

    /* 3: firmware facts */
    find_framebuffer(bi);
    find_acpi(bi);
    {
        struct boot_wall w = { 0 };
        efi_time t;
        if (st->runtime_services && st->runtime_services->get_time && st->runtime_services->get_time(&t, NULL) == 0) {
            w.tsc = rdtsc();
            w.time = t;
            w.magic = BOOT_WALL_MAGIC;
        }
        memcpy((void *)(uintptr_t)(bi_pa + BOOT_WALL_OFFSET), &w, sizeof(w));
    }
    mark("GOP + ACPI");

    /* Identity map up to the end of RAM (at least 4 GiB, at most 512 GiB). */
    uint64_t map_size = 0, key, desc_size;
    uint32_t desc_ver;
    s = bs->get_memory_map(&map_size, NULL, &key, &desc_size, &desc_ver);
    if (s != EFI_BUFFER_TOO_SMALL || desc_size < sizeof(efi_memory_descriptor))
        return fail(s, "GetMemoryMap failed");
    uint64_t cap = map_size + 16 * desc_size;
    uint8_t *map;
    if ((s = bs->allocate_pool(EFI_LOADER_DATA, cap, (void **)&map)))
        return fail(s, "out of memory for the memory map");
    map_size = cap;
    if ((s = bs->get_memory_map(&map_size, (efi_memory_descriptor *)map, &key, &desc_size, &desc_ver)))
        return fail(s, "GetMemoryMap failed");
    uint64_t top = 4 * GIB;
    for (uint64_t off = 0; off + desc_size <= map_size; off += desc_size) {
        const efi_memory_descriptor *d = (const efi_memory_descriptor *)(map + off);
        uint64_t end = d->phys_start + d->pages * PAGE;
        if (e820_type(d->type) == MMAP_USABLE && end > top && end <= 512 * GIB)
            top = end;
    }
    top = (top + GIB - 1) & ~(GIB - 1);
    if (!gb_pages && top > 64 * GIB)
        top = 64 * GIB;                          /* 2 MiB pages: 64 PDs at most in low memory */
    uint64_t cr3;
    if ((s = build_tables(top, gb_pages, kbase, &cr3)))
        return s;
    mark("page tables");

    struct handoff *ho = (struct handoff *)(uintptr_t)(ho_pa + PAGE);
    memcpy((void *)(uintptr_t)ho_pa, handoff_start, (size_t)((uintptr_t)handoff_end - (uintptr_t)handoff_start));
    ho->bootinfo = bi_pa;
    ho->cr3 = cr3;
    ho->entry = h->entry + delta;
    ho->stack = ho_pa + 2 * PAGE;
    ho->gdt[1] = 0x00CF9A000000FFFFull;          /* 0x08 code32 */
    ho->gdt[2] = 0x00CF92000000FFFFull;          /* 0x10 data */
    ho->gdt[3] = 0x00AF9A000000FFFFull;          /* 0x18 code64 */
    ho->gdt_limit = sizeof(ho->gdt) - 1;
    ho->gdt_base = (uint64_t)(uintptr_t)ho->gdt;

    say("D-OS: exiting boot services (identity map %u GiB, %s pages)\n", top / GIB, gb_pages ? "1 GiB" : "2 MiB");
    mark("hand-off");

    /* 5: the map key must be current: the first attempt can fail if the map changed (e.g. the
     * console output above allocated); then only GetMemoryMap and ExitBootServices are allowed. */
    map_size = cap;
    if ((s = bs->get_memory_map(&map_size, (efi_memory_descriptor *)map, &key, &desc_size, &desc_ver)))
        return fail(s, "GetMemoryMap failed");
    if (bs->exit_boot_services(image, key)) {
        map_size = cap;
        if (bs->get_memory_map(&map_size, (efi_memory_descriptor *)map, &key, &desc_size, &desc_ver) ||
            bs->exit_boot_services(image, key))
            late_fatal("D-OS: UEFI loader: ExitBootServices failed\r\n");
    }
    /* No firmware services from here on. */
    uint32_t count;
    if (!convert_map(map, map_size, desc_size, mm, &count, top))
        late_fatal("D-OS: UEFI loader: memory map does not fit BootInfo\r\n");
    bi->mmap_count = count;
    mark("exit boot svc");
    timing.magic = BOOT_TIMING_MAGIC;
    timing.console_cycles = con_cycles;
    memcpy((void *)(uintptr_t)(bi_pa + BOOT_TIMING_OFFSET), &timing, sizeof(timing));
    bi->tsc_loader_exit = rdtsc();
    ((void (*)(struct handoff *))(uintptr_t)ho_pa)(ho);
    late_fatal("D-OS: UEFI loader: hand-off returned\r\n");
}
