/* UEFI loader step times (optional, not part of the BootInfo ABI): written by the UEFI loader in the
 * BootInfo page at BOOT_TIMING_OFFSET, after the BootInfo itself. The kernel copies it while the
 * page is still mapped and prints the steps in milliseconds (it knows the TSC frequency; the
 * loader does not). Ignored unless the magic matches and the stamps never go backwards. */
#define BOOT_TIMING_OFFSET 2048u
#define BOOT_TIMING_MAGIC  0x31454D4954534F44ull   /* "DOSTIME1" */
#define BOOT_TIMING_STEPS  12u
struct boot_timing_step {
    char     name[16];      /* NUL-terminated */
    uint64_t tsc;           /* TSC at the end of the step */
};
struct boot_timing {
    uint64_t magic;
    uint32_t count;
    uint32_t reserved;
    uint64_t console_cycles; /* time spent in firmware text output (part of the steps) */
    struct boot_timing_step step[BOOT_TIMING_STEPS];
};
_Static_assert(sizeof(struct boot_timing) == 24 + 24 * BOOT_TIMING_STEPS, "boot timing layout");
_Static_assert(BOOT_TIMING_OFFSET >= 416 && BOOT_TIMING_OFFSET + sizeof(struct boot_timing) <= 4096,
               "boot timing fits in the BootInfo page after the BootInfo");

/* Wall-clock time at boot (optional, not part of the BootInfo ABI): the UEFI loader stores what
 * GetTime said, and the TSC when it said it, at BOOT_WALL_OFFSET in the BootInfo page. The kernel
 * hands it to the clock service; under BIOS there is none (the clock service reads the RTC). */
#define BOOT_WALL_OFFSET 3584u
#define BOOT_WALL_MAGIC  0x314C4C4157534F44ull   /* "DOSWALL1" */
struct boot_wall {
    uint64_t magic;
    uint64_t tsc;           /* TSC right after GetTime returned */
    efi_time time;
};
_Static_assert(sizeof(struct boot_wall) == 32, "boot wall layout");
_Static_assert(BOOT_TIMING_OFFSET + sizeof(struct boot_timing) <= BOOT_WALL_OFFSET && BOOT_WALL_OFFSET + 32 <= 4096,
               "boot wall time fits in the BootInfo page after the step times");

static struct boot_timing timing;           /* copied into the BootInfo page at the end */
static uint64_t con_cycles;

static uint64_t rdtsc(void);
static void mark(const char *name)
{
    if (timing.count >= BOOT_TIMING_STEPS)
        return;
    struct boot_timing_step *s = &timing.step[timing.count++];
    for (size_t i = 0; i < sizeof(s->name) - 1 && name[i]; i++)
        s->name[i] = name[i];
    s->tsc = rdtsc();
}
